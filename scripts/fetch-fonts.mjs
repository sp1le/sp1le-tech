/**
 * Downloads the woff2 files we actually use and writes a local @font-face sheet.
 * Self-hosting keeps the page free of third-party requests and removes the
 * font-swap flash that a render-blocking Google Fonts stylesheet introduces.
 *
 * Run: node scripts/fetch-fonts.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

const UA =
  'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';

/** Only the subsets the site can actually render: English + Ukrainian. */
const KEEP = new Set(['latin', 'latin-ext', 'cyrillic']);

const FAMILIES = [
  { query: 'Geologica:wght@300..700', slug: 'geologica' },
  { query: 'IBM+Plex+Sans:wght@400..600', slug: 'plex-sans' },
  { query: 'IBM+Plex+Mono:wght@400;600', slug: 'plex-mono' },
];

const OUT_DIR = join(process.cwd(), 'public', 'fonts');
const CSS_OUT = join(process.cwd(), 'src', 'styles', 'fonts.css');

/** Splits a Google Fonts stylesheet into `{ subset, block }` pairs. */
function parseBlocks(css) {
  const blocks = [];
  const re = /\/\*\s*([a-z-]+)\s*\*\/\s*(@font-face\s*\{[^}]*\})/g;
  let match;
  while ((match = re.exec(css)) !== null) {
    blocks.push({ subset: match[1], block: match[2] });
  }
  return blocks;
}

const pick = (block, prop) => block.match(new RegExp(`${prop}:\\s*([^;]+);`))?.[1]?.trim();

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  const sheets = [
    '/* Generated by scripts/fetch-fonts.mjs - do not edit by hand. */',
  ];

  for (const family of FAMILIES) {
    const url = `https://fonts.googleapis.com/css2?family=${family.query}&display=swap`;
    const css = await fetch(url, { headers: { 'User-Agent': UA } }).then((r) => r.text());

    let index = 0;
    for (const { subset, block } of parseBlocks(css)) {
      if (!KEEP.has(subset)) continue;

      const src = block.match(/url\((https:\/\/[^)]+\.woff2)\)/)?.[1];
      if (!src) continue;

      const name = `${family.slug}-${subset}${index++ ? `-${index}` : ''}.woff2`;
      const bytes = Buffer.from(await fetch(src).then((r) => r.arrayBuffer()));
      await writeFile(join(OUT_DIR, name), bytes);

      sheets.push(
        [
          '@font-face {',
          `  font-family: ${pick(block, 'font-family')};`,
          `  font-style: ${pick(block, 'font-style')};`,
          `  font-weight: ${pick(block, 'font-weight')};`,
          '  font-display: swap;',
          `  src: url('/fonts/${name}') format('woff2');`,
          `  unicode-range: ${pick(block, 'unicode-range')};`,
          '}',
        ].join('\n'),
      );

      console.log(`${name.padEnd(34)} ${(bytes.length / 1024).toFixed(1)} KB`);
    }
  }

  await writeFile(CSS_OUT, sheets.join('\n\n') + '\n');
  console.log(`\nWrote ${CSS_OUT}`);
}

await main();
